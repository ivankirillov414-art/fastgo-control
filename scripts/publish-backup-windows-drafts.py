"""Stage the exact bounded Windows CI candidates; never promote a feed or release."""
import base64
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time

REPO = "ivankirillov414-art/fastgo-control"
BRANCH = "codex/backup-seven-days-20261107"
RUN = os.environ["BUILD_RUN"]
SHA = os.environ["BUILD_SHA"]
assert re.fullmatch(r"[0-9]+", RUN) and re.fullmatch(r"[0-9a-f]{40}", SHA)
APPS = (
    ("desktop", "fastgo-desktop", "1.0.75", "fastgo-windows-v1.0.75", "FastGo-Setup-1.0.75-Windows-x64.exe", "packaged-backup-runtime.txt"),
    ("warehouse-desktop", "fastgo-warehouse-desktop", "1.0.64", "fastgo-warehouse-v1.0.64", "FastGo-Warehouse-Setup-1.0.64-Windows-x64.exe", "packaged-warehouse-backup-runtime.txt"),
)


def gh(*args):
    return subprocess.run(["gh", *args], check=True, capture_output=True).stdout


def api(endpoint):
    return json.loads(gh("api", "--method", "GET", "-H", "X-GitHub-Api-Version: 2022-11-28", f"repos/{REPO}/{endpoint}"))


def optional_release(tag):
    result = subprocess.run(["gh", "api", "--method", "GET", f"repos/{REPO}/releases/tags/{tag}"], capture_output=True)
    if result.returncode == 0:
        return json.loads(result.stdout)
    if b"HTTP 404" in result.stderr:
        return None
    raise RuntimeError(result.stderr.decode("utf-8", errors="replace"))


def source_bytes(name):
    result = api(f"contents/{name}?ref={SHA}")
    assert result["encoding"] == "base64"
    return base64.b64decode(result["content"], validate=False)


def sha(path, algorithm="sha256", encoding="hex"):
    digest = hashlib.new(algorithm)
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest() if encoding == "hex" else base64.b64encode(digest.digest()).decode("ascii")


def run_gate(wait=False):
    for attempt in range(31 if wait else 1):
        run = api(f"actions/runs/{RUN}")
        assert run["head_sha"] == SHA and run["head_branch"] == BRANCH
        assert run["head_repository"]["full_name"] == REPO and run["event"] == "push"
        assert run["path"] == ".github/workflows/backup-windows-native.yml"
        if run["status"] == "completed":
            assert run["conclusion"] == "success", "Native build did not pass; no draft may be created"
            jobs = api(f"actions/runs/{RUN}/jobs?per_page=100")["jobs"]
            assert len(jobs) == 1 and jobs[0]["conclusion"] == "success"
            steps = {step["name"]: step["conclusion"] for step in jobs[0]["steps"]}
            for name in ("Build common Windows update candidate", "Exercise packaged Electron SQLite and ASAR worker paths", "Build standalone warehouse update candidate", "Exercise standalone warehouse ASAR worker", "Record immutable candidate hashes"):
                assert steps.get(name) == "success", f"Missing gate: {name}"
            artifacts = api(f"actions/runs/{RUN}/artifacts?per_page=100")["artifacts"]
            for name in ("backup-windows-native-evidence", "backup-windows-update-candidates"):
                matches = [item for item in artifacts if item["name"] == name and not item["expired"]]
                assert len(matches) == 1 and matches[0]["workflow_run"]["head_sha"] == SHA
            return run, jobs[0], artifacts
        if not wait or attempt == 30:
            raise RuntimeError("Native build has not completed")
        time.sleep(30)
    raise AssertionError("Unreachable")


def channel_state():
    latest = api("releases/latest")
    assert latest["tag_name"].startswith("fastgo-windows-v"), "Common Windows must own global latest"
    feed = api("contents/warehouse/update/latest.yml?ref=main")
    return {"latest_id": latest["id"], "latest_tag": latest["tag_name"], "warehouse_feed_blob": feed["sha"]}


def validate_feed(path, version, name, tag, executable):
    text = path.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    # Accept only the single-file NSIS feed grammar generated by this build.
    match = re.fullmatch(r"version: ([^\n]+)\nfiles:\n  - url: ([^\n]+)\n    sha512: ([A-Za-z0-9+/=]+)\n    size: ([0-9]+)\npath: ([^\n]+)\nsha512: ([A-Za-z0-9+/=]+)\nreleaseDate: ([^\n]+)\n?", text)
    assert match, "Unexpected update manifest structure"
    allowed = {name, f"https://github.com/{REPO}/releases/download/{tag}/{name}"}
    assert match[1] == version and match[2] in allowed and match[5] in allowed
    assert int(match[4]) == executable.stat().st_size
    digest = sha(executable, "sha512", "base64")
    assert match[3] == match[6] == digest, "NSIS SHA512 mismatch"
    return {"sha512_base64": digest, "bytes": int(match[4])}


def drafts():
    run, job, artifacts = run_gate()
    before = channel_state()
    evidence_root = Path("native-evidence")
    evidence = json.loads((evidence_root / "windows-backup-candidates.json").read_text(encoding="utf-8-sig"))
    assert evidence["status"] == "PASS" and evidence["source"] == SHA
    prepared = []
    for folder, app, version, tag, name, proof_name in APPS:
        root = Path("candidates") / folder / "dist"
        names = [name, name + ".blockmap", "latest.yml", "release-content.json"]
        records = {}
        for file_name in names:
            file = root / file_name
            assert file.is_file() and not file.is_symlink()
            matches = [item for item in evidence["files"] if item["app"] == folder and item["version"] == version and item["name"] == file_name]
            assert len(matches) == 1, f"Candidate missing from successful build: {file_name}"
            item = matches[0]
            assert item["bytes"] == file.stat().st_size and item["sha256"] == sha(file), f"Build SHA256 mismatch: {file_name}"
            records[file_name] = {"bytes": file.stat().st_size, "sha256": sha(file), "sha512": sha(file, "sha512")}
        exe = root / name
        with exe.open("rb") as stream:
            assert stream.read(2) == b"MZ", "Windows installer header missing"
        feed = validate_feed(root / "latest.yml", version, name, tag, exe)
        manifest = json.loads((root / "release-content.json").read_text(encoding="utf-8-sig"))
        assert manifest["schema"] == 1 and manifest["app"] == app and manifest["version"] == version
        payload = {key: manifest[key] for key in ("schema", "app", "version", "files", "resources", "inputs")}
        encoded = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        assert hashlib.sha256(encoded).hexdigest() == manifest["fingerprint"], "Content fingerprint mismatch"
        package = json.loads(source_bytes(folder + "/package.json"))
        assert package["version"] == version and package["name"] == app
        expected_inputs = {"package.json", "package-lock.json", package["build"]["nsis"]["include"]}
        assert set(manifest["inputs"]) == expected_inputs
        for input_name, digest in manifest["inputs"].items():
            assert hashlib.sha256(source_bytes(folder + "/" + input_name)).hexdigest() == digest, f"Source input differs: {input_name}"
        proof_file = evidence_root / proof_name
        proofs = [json.loads(line) for line in proof_file.read_text(encoding="utf-8-sig").splitlines() if line.startswith("{")]
        assert len(proofs) == 1
        proof = proofs[0]
        assert proof["status"] == "PASS" and proof["integrity"] == "ok" and proof["outbox"] == 1 and proof["production_requests"] == 0
        assert proof["runtime"]["electron"] == "44.7.0"
        assert proof["asar"].replace("\\", "/").endswith(f"/{folder}/dist/win-unpacked/resources/app.asar")
        info = {"app": app, "version": version, "source": SHA, "run": int(RUN), "job": job["id"], "content_fingerprint": manifest["fingerprint"], "manifest": feed, "files": records, "packaged_proof": proof, "draft_only": True}
        (root / "WINDOWS_BACKUP_BUILD.json").write_text(json.dumps(info, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        for algorithm in ("sha256", "sha512"):
            (root / (algorithm.upper() + "SUMS.txt")).write_text("".join(f"{sha(root / n, algorithm)}  {n}\n" for n in names), encoding="ascii")
        prepared.append((tag, root, info, names + ["WINDOWS_BACKUP_BUILD.json", "SHA256SUMS.txt", "SHA512SUMS.txt"]))

    releases = []
    # Validate both apps completely before creating either draft.
    for tag, root, info, names in prepared:
        existing = optional_release(tag)
        if existing:
            assert existing["draft"] and not existing["prerelease"] and existing["target_commitish"] == SHA, "Refusing to replace a published or different candidate"
        else:
            notes = root / "DRAFT_NOTES.txt"
            notes.write_text(f"Windows daily backup candidate {info['version']}.\nBuild: {run['html_url']}\nSource: {SHA}\nPackaged Electron/SQLite/ASAR verification passed on isolated fixtures.\nDraft only; production update channels and databases remain unchanged.\n", encoding="utf-8")
            gh("release", "create", tag, "--repo", REPO, "--draft", "--latest=false", "--target", SHA, "--title", f"FastGo {'Windows' if info['app'] == 'fastgo-desktop' else 'Склад'} {info['version']}", "--notes-file", str(notes))
        release = api(f"releases/tags/{tag}")
        assert release["draft"] and release["target_commitish"] == SHA
        assets = {asset["name"]: asset for asset in release["assets"]}
        assert set(assets).issubset(names), "Unexpected existing draft assets"
        for name in names:
            file = root / name
            if name not in assets:
                gh("release", "upload", tag, str(file), "--repo", REPO)
        release = api(f"releases/tags/{tag}")
        assert release["draft"] and not release["prerelease"] and release["target_commitish"] == SHA
        assert {asset["name"] for asset in release["assets"]} == set(names)
        readback = Path("remote-readback") / tag
        readback.mkdir(parents=True, exist_ok=True)
        asset_results = []
        for asset in release["assets"]:
            name = asset["name"]
            file = root / name
            assert asset["size"] == file.stat().st_size and asset["state"] == "uploaded"
            assert asset.get("digest") in (None, "sha256:" + sha(file)), "Published asset digest mismatch"
            # All installer readback takes place on the remote runner, never on a laptop.
            gh("release", "download", tag, "--repo", REPO, "--dir", str(readback), "--pattern", name, "--skip-existing")
            assert sha(readback / name) == sha(file), "Remote draft asset readback mismatch"
            asset_results.append({"id": asset["id"], "name": name, "bytes": asset["size"], "sha256": sha(file), "sha512": sha(file, "sha512"), "url": asset["browser_download_url"], "remote_readback": "PASS"})
        releases.append({**info, "release_id": release["id"], "tag": tag, "draft": release["draft"], "make_latest": False, "url": release["html_url"], "assets": asset_results})
    after = channel_state()
    assert after == before, "A live channel changed while staging drafts; do not promote"
    result = {"status": "DRAFTS_READY", "source": SHA, "build_run": int(RUN), "build_job": job["id"], "build_url": run["html_url"], "publisher_run": os.environ["GITHUB_RUN_ID"], "publisher_sha": os.environ["GITHUB_SHA"], "drafts": releases, "artifact_retention_days": 7, "source_artifacts": artifacts, "channels_before": before, "channels_after": after, "feeds_changed": False, "production_deployed": False, "local_installer_downloads": 0, "limitations": ["Drafts require final coordinator release acceptance and promotion.", "Packaged backup runtime uses isolated fixtures, not production Postgres or physical hardware.", "No service/payment scenarios were added or repeated."]}
    Path("WINDOWS_BACKUP_DRAFT_RESULT.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": result["status"], "build": run["html_url"], "drafts": [item["url"] for item in releases], "channels_unchanged": True}))


if __name__ == "__main__":
    if sys.argv[1:] == ["gate"]:
        run_gate(wait=True)
        print("Exact Windows native build and both immutable artifacts accepted")
    elif sys.argv[1:] == ["drafts"]:
        drafts()
    else:
        raise SystemExit("Expected gate or drafts")
