import fs from 'node:fs';
import {equipmentData} from '../warehouse/equipment-data.js';

// Keep intake offline and small: no prices, stock or offer metadata are copied.
// Unknown brands and Cyrillic foreign model names need editorial review first.
const seen=new Set();
const baseline=JSON.parse(fs.readFileSync(new URL('../docs/repair-intake-reference-baseline.json',import.meta.url),'utf8')).items;
const candidates=[...baseline.map(x=>({...x,offers:[{url:x.source}]})),...equipmentData.items];
const items=candidates.filter(item=>{
 const key=(item.brand+' '+item.model).toLowerCase();
 if(!item.brand||!item.model||item.brand==='Не указана'||/[а-яё]/i.test(item.brand+' '+item.model)||seen.has(key))return false;
 if(!item.offers?.some(offer=>/^https:\/\//.test(offer.url||'')))return false;
 seen.add(key);return true;
}).map(item=>({brand:item.brand,model:item.model,source:item.offers.find(offer=>/^https:\/\//.test(offer.url||'')).url}));
const content='// Generated by scripts/build-intake-reference.mjs from sourced equipment data.\nexport const intakeReference='+JSON.stringify(items)+';\n';
const target=new URL('../workshop/intake-reference-data.js',import.meta.url);
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==content)throw Error('Intake reference is stale; run node scripts/build-intake-reference.mjs');
}else fs.writeFileSync(target,content);
console.log('Intake reference: '+items.length+' sourced names');
